// Generate the browser catalog from the independently rendered, checked-in parts.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const directory = new URL("../docs/shared/bricks/e500-v1/", import.meta.url);
const destination = new URL("../docs/shared/brick-e500.js", import.meta.url);
const metadata = JSON.parse(await readFile(new URL("metadata.json", directory), "utf8"));
const digest = createHash("sha256");
const steps = [];
for (const step of metadata.steps) {
  const parts = [];
  for (const part of step.parts) {
    if (!/^(?:assets\/)?p\d+-[123]\.png$/.test(part.file)) throw Error(`Invalid E500 asset: ${part.file}`);
    const bytes = await readFile(new URL(part.file, directory));
    if (createHash("sha256").update(bytes).digest("hex") !== part.sha256) throw Error(`E500 asset differs from its manifest: ${part.file}`);
    digest.update(part.file).update(bytes);
    const { id, name, z, box, imageBox, file } = part;
    parts.push({ id, name, z, box, imageBox, file });
  }
  steps.push({ title: step.title, parts });
}
const data = {
  id: metadata.id, title: metadata.title, series: metadata.series,
  viewBox: metadata.viewBox, assetVersion: digest.digest("hex").slice(0, 16), steps,
};
const source = `// Generated by scripts/build-e500-runtime.mjs. Edit scripts/e500-art/ to change the model.
(function (root) {
  "use strict";
  const data = ${JSON.stringify(data)};
  const scriptUrl = typeof document !== "undefined" && document.currentScript?.src;
  const base = scriptUrl ? new URL("bricks/e500-v1/", scriptUrl).href : "shared/bricks/e500-v1/";
  const escapeAttribute = value => value.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
  for (const step of data.steps) for (const part of step.parts) {
    const b = part.imageBox;
    part.svg = '<g aria-hidden="true"><image x="' + b.x + '" y="' + b.y + '" width="' + b.width + '" height="' + b.height + '" href="' + escapeAttribute(base + part.file + '?v=' + data.assetVersion) + '"/></g>';
  }
  root.KidsBrickE500 = data;
})(typeof window === "undefined" ? globalThis : window);
`;
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")).replace(/\r\n/g, "\n") !== source) throw Error("E500 runtime is stale; run node scripts/build-e500-runtime.mjs");
  console.log("E500 runtime matches all 42 checked-in images.");
} else {
  await writeFile(destination, source);
  console.log(`Generated E500 runtime (${Buffer.byteLength(source)} bytes).`);
}
